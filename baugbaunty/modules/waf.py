"""Web Application Firewall (WAF) detection.

Knowing whether a target sits behind a WAF — and which one — tells you how to
pace and shape later testing and helps explain odd blocking behaviour. This
module fingerprints common WAFs from response headers, cookies and the response
to a single benign "suspicious-looking" request. It is observational and
non-intrusive; the trigger payload is harmless and sent once per service.
"""

from __future__ import annotations

import re
from urllib.parse import urlencode

from .base import Context, Module

# WAF signatures: name -> list of (where, compiled-pattern).
# where in {"header", "cookie", "server", "body"}
_SIGNATURES: dict[str, list[tuple[str, re.Pattern[str]]]] = {
    "Cloudflare": [("header", re.compile(r"cf-ray|__cfduid|cf-cache-status", re.I)),
                   ("server", re.compile(r"cloudflare", re.I))],
    "Akamai": [("header", re.compile(r"akamai|x-akamai-transformed", re.I)),
               ("server", re.compile(r"akamaighost", re.I))],
    "Imperva/Incapsula": [("cookie", re.compile(r"incap_ses|visid_incap", re.I)),
                          ("header", re.compile(r"x-iinfo|x-cdn:\s*incapsula", re.I))],
    "AWS WAF / CloudFront": [("header", re.compile(r"x-amz-cf-id|x-amzn-requestid", re.I)),
                             ("server", re.compile(r"awselb|cloudfront", re.I))],
    "Sucuri": [("header", re.compile(r"x-sucuri-id|x-sucuri-cache", re.I)),
               ("server", re.compile(r"sucuri", re.I))],
    "F5 BIG-IP ASM": [("cookie", re.compile(r"TS[0-9a-f]{6,}|BIGipServer", re.I)),
                      ("header", re.compile(r"x-waf-event", re.I))],
    "Barracuda": [("cookie", re.compile(r"barra_counter_session|BNI__", re.I))],
    "Fortinet FortiWeb": [("cookie", re.compile(r"FORTIWAFSID", re.I))],
    "Wordfence": [("body", re.compile(r"Generated by Wordfence", re.I))],
    "Sucuri CloudProxy": [("body", re.compile(r"Access Denied - Sucuri Website Firewall", re.I))],
    "ModSecurity": [("server", re.compile(r"mod_security|NOYB", re.I)),
                    ("body", re.compile(r"Mod_Security|This error was generated by Mod_Security", re.I))],
    "Azure Front Door/WAF": [("header", re.compile(r"x-azure-ref|x-fd-healthprobe", re.I))],
    "StackPath/MaxCDN": [("server", re.compile(r"stackpath|netdna", re.I))],
}

# A harmless string that often trips signature-based WAFs without doing harm.
# URL-encoded so it is always a valid request line.
_TRIGGER = "?" + urlencode({"bbxwaf": "1' OR '1'='1"})


class WafModule(Module):
    name = "waf"
    active = True

    def __init__(self, services: list[str] | None = None) -> None:
        self.services = services

    def _bases(self, ctx: Context) -> list[str]:
        if self.services:
            return [s for s in self.services if ctx.scope.is_allowed(s)]
        return [s["url"] for s in ctx.store.services() if ctx.scope.is_allowed(s["url"])]

    def run(self, ctx: Context) -> dict:
        bases = self._bases(ctx)
        if not bases:
            ctx.log.warn("[waf] no in-scope services; run probe first")
            return {"checked": 0, "detected": 0}

        detected = 0
        for base in bases:
            if self._detect(ctx, base.rstrip("/")):
                detected += 1
        ctx.log.success(f"[waf] {detected}/{len(bases)} service(s) behind a known WAF")
        return {"checked": len(bases), "detected": detected}

    def _detect(self, ctx: Context, base: str) -> bool:
        baseline = ctx.http.get(base)
        if not baseline.ok:
            return False
        hits = self._match(baseline)

        # One benign trigger request: a WAF may reveal itself by blocking it.
        trig = ctx.http.get(base + "/" + _TRIGGER)
        if trig.ok:
            hits |= self._match(trig)
            if trig.status in (403, 406, 419, 429, 503) and not hits:
                hits.add("Generic WAF (blocked a benign suspicious request)")

        if not hits:
            return False
        for waf in sorted(hits):
            ctx.store.add_finding(
                target=base, module="waf",
                name=f"WAF detected: {waf}", severity="info",
                evidence=f"Response fingerprints matched '{waf}' on {base}",
                waf=waf,
            )
        ctx.store.add_service(base, data={"waf": sorted(hits)})
        ctx.log.info(f"[waf] {base}: {', '.join(sorted(hits))}")
        return True

    def _match(self, resp) -> set[str]:
        header_blob = "\n".join(f"{k}: {v}" for k, v in resp.headers.items())
        cookie = resp.header("set-cookie")
        server = resp.header("server")
        body = resp.text(limit=50_000)
        where = {"header": header_blob, "cookie": cookie, "server": server, "body": body}
        found: set[str] = set()
        for waf, sigs in _SIGNATURES.items():
            for loc, pat in sigs:
                if pat.search(where.get(loc, "")):
                    found.add(waf)
                    break
        return found
